from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path


@dataclass
class Atom:
    atom_id: int
    atom_type: int
    x: float
    y: float
    z: float


@dataclass
class Structure:
    bounds: tuple[float, float, float, float, float, float]
    atoms: list[Atom]


def read_coordinate_txt(filepath: str | Path, padding: float = 1.0) -> Structure:
    """Read plain text rows in either `x y z` or `id type x y z` format."""
    atoms: list[Atom] = []
    for line_number, line in enumerate(Path(filepath).read_text(encoding="utf-8").splitlines(), 1):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        values = line.replace(",", " ").split()
        try:
            if len(values) == 3:
                atom_id = len(atoms) + 1
                atom_type = 1
                x, y, z = (float(value) for value in values)
            elif len(values) >= 5:
                atom_id = int(values[0])
                atom_type = int(values[1])
                x, y, z = (float(value) for value in values[2:5])
            else:
                raise ValueError("use x y z or id type x y z")
        except ValueError as exc:
            raise ValueError(f"Invalid data at line {line_number}: {line!r} ({exc})") from exc
        atoms.append(Atom(atom_id, atom_type, x, y, z))

    if not atoms:
        raise ValueError("The input file does not contain coordinate rows")
    xs = [atom.x for atom in atoms]
    ys = [atom.y for atom in atoms]
    zs = [atom.z for atom in atoms]
    bounds = (
        min(xs) - padding, max(xs) + padding,
        min(ys) - padding, max(ys) + padding,
        min(zs) - padding, max(zs) + padding,
    )
    return Structure(bounds, atoms)


def read_lammps_dump(filepath: str | Path, frame: int = -1) -> Structure:
    """Read one frame from a LAMMPS dump containing id, type, and coordinates."""
    lines = Path(filepath).read_text(encoding="utf-8").splitlines()
    frames: list[Structure] = []
    index = 0
    while index < len(lines):
        if lines[index].strip() != "ITEM: TIMESTEP":
            index += 1
            continue
        index += 2
        if lines[index].strip() != "ITEM: NUMBER OF ATOMS":
            raise ValueError("Invalid LAMMPS dump: missing atom count")
        atom_count = int(lines[index + 1].strip())
        index += 2
        if not lines[index].startswith("ITEM: BOX BOUNDS"):
            raise ValueError("Invalid LAMMPS dump: missing box bounds")
        index += 1
        bounds: list[float] = []
        for _ in range(3):
            values = lines[index].split()
            bounds.extend((float(values[0]), float(values[1])))
            index += 1
        if not lines[index].startswith("ITEM: ATOMS "):
            raise ValueError("Invalid LAMMPS dump: missing atom columns")
        columns = lines[index].removeprefix("ITEM: ATOMS ").split()
        coordinate_names = ("x", "y", "z") if all(name in columns for name in ("x", "y", "z")) else ("xu", "yu", "zu")
        required = ("id", "type", *coordinate_names)
        if not all(name in columns for name in required):
            raise ValueError("LAMMPS dump must contain id, type, and x/y/z or xu/yu/zu")
        positions = {name: columns.index(name) for name in required}
        index += 1
        atoms = []
        for _ in range(atom_count):
            values = lines[index].split()
            atoms.append(Atom(
                int(values[positions["id"]]), int(values[positions["type"]]),
                float(values[positions[coordinate_names[0]]]),
                float(values[positions[coordinate_names[1]]]),
                float(values[positions[coordinate_names[2]]]),
            ))
            index += 1
        frames.append(Structure(tuple(bounds), atoms))
    if not frames:
        raise ValueError("The input file does not contain a LAMMPS dump frame")
    try:
        return frames[frame]
    except IndexError as exc:
        raise ValueError(f"Frame {frame} is outside the input file") from exc


def read_structure(filepath: Path, frame: int, padding: float) -> Structure:
    first_line = filepath.read_text(encoding="utf-8").lstrip()[:40]
    if first_line.startswith("ITEM: TIMESTEP"):
        return read_lammps_dump(filepath, frame)
    return read_coordinate_txt(filepath, padding)


def write_data_file(structure: Structure, filepath: Path, mass: float) -> None:
    xlo, xhi, ylo, yhi, zlo, zhi = structure.bounds
    atom_type_count = max(atom.atom_type for atom in structure.atoms)
    with filepath.open("w", encoding="utf-8") as file:
        file.write("Generated by basic_config_generator.py\n\n")
        file.write(f"{len(structure.atoms)} atoms\n{atom_type_count} atom types\n\n")
        file.write(f"{xlo} {xhi} xlo xhi\n{ylo} {yhi} ylo yhi\n{zlo} {zhi} zlo zhi\n\n")
        file.write("Masses\n\n")
        for atom_type in range(1, atom_type_count + 1):
            file.write(f"{atom_type} {mass:.10g}\n")
        file.write("\nAtoms # atomic\n\n")
        for atom in sorted(structure.atoms, key=lambda item: item.atom_id):
            file.write(f"{atom.atom_id} {atom.atom_type} {atom.x:.10g} {atom.y:.10g} {atom.z:.10g}\n")


def write_input_file(data_name: str, filepath: Path, args: argparse.Namespace) -> None:
    lines = [
        "units real", "dimension 3", "boundary p p p", "atom_style atomic", "",
        f"read_data {data_name}", "", f"pair_style {args.pair_style}",
        f"pair_coeff {args.pair_coeff}", "", f"timestep {args.timestep}",
        f"velocity all create {args.temperature} 12345 mom yes rot no",
        f"fix integration all nve", f"thermo {args.thermo}",
        f"dump trajectory all custom {args.dump_every} dump.lammpstrj id type x y z vx vy vz",
        "", f"run {args.run_steps}", "",
    ]
    filepath.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Convert a coordinate TXT or LAMMPS dump into runnable LAMMPS files.")
    parser.add_argument("input", type=Path, help="Input .txt or LAMMPS dump")
    parser.add_argument("-o", "--output", type=Path, default=Path("in.run"), help="LAMMPS input script to create")
    parser.add_argument("--data", type=Path, help="Data file to create (default: next to input script)")
    parser.add_argument("--frame", type=int, default=-1, help="Dump frame to use; -1 means the last frame")
    parser.add_argument("--padding", type=float, default=1.0, help="Box padding for plain coordinate TXT files")
    parser.add_argument("--mass", type=float, default=1.0, help="Mass assigned to each atom type")
    parser.add_argument("--pair-style", default="lj/cut 10.0")
    parser.add_argument("--pair-coeff", default="* * 1.0 1.0")
    parser.add_argument("--timestep", type=float, default=0.001)
    parser.add_argument("--temperature", type=float, default=300.0)
    parser.add_argument("--thermo", type=int, default=100)
    parser.add_argument("--dump-every", type=int, default=100)
    parser.add_argument("--run-steps", type=int, default=1000)
    args = parser.parse_args()

    args.output.parent.mkdir(parents=True, exist_ok=True)
    data_path = args.data or args.output.with_suffix(".data")
    data_path.parent.mkdir(parents=True, exist_ok=True)
    structure = read_structure(args.input, args.frame, args.padding)
    write_data_file(structure, data_path, args.mass)
    write_input_file(data_path.name, args.output, args)
    print(f"Created {args.output} and {data_path} ({len(structure.atoms)} atoms)")


if __name__ == "__main__":
    main()